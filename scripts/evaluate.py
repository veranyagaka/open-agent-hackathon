"""
scripts/evaluate.py

Back-test StockyWhy on the 16 planted cases in data/cases/.

This is the ONLY code that reads eval/answer_key.csv. The agent runs on each
case exactly as a user would ask it, with a fresh, empty case memory per case,
and its answer is scored afterwards.

    python scripts/evaluate.py                # all 16 cases
    python scripts/evaluate.py --set noisy    # one set

Writes eval/results.json and eval/RESULTS.md.
"""

import argparse
import contextlib
import csv
import io
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)
os.environ.setdefault("SAMPLE_MODE", "true")

from engines.hmem import CaseMemory  # noqa: E402
from llm_client import llm_enabled  # noqa: E402
from orchestrator import StockyWhy  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", choices=["normal", "noisy", "all"], default="all")
    args = ap.parse_args()

    questions = list(csv.DictReader((ROOT / "data/cases/questions.csv").open()))
    truth = {r["dataset"]: r for r in csv.DictReader((ROOT / "eval/answer_key.csv").open())}

    rows = []
    for q in questions:
        if args.set != "all" and f"/{args.set}/" not in q["dataset"]:
            continue
        # Fresh memory per case so no answer leaks between cases
        with tempfile.TemporaryDirectory() as tmp:
            agent = StockyWhy(memory=CaseMemory(Path(tmp) / "hmem.json"))
            with contextlib.redirect_stdout(io.StringIO()):
                r = agent.run(q["dataset"], q["facility_id"], q["commodity"],
                              q["month"], interactive=False)
        t = truth[q["dataset"]]
        expected, also = t["true_primary_cause"], t["also_contributing"]
        supported = [h["hypothesis_name"] for h in r.get("ranked_hypotheses", [])
                     if h.get("verdict") == "supported"]
        predicted = (r.get("verified_cause") or {}).get("hypothesis_name") or r.get("status")
        actions = [e.get("action") for e in r.get("trace", [])]
        rows.append({
            "dataset": q["dataset"], "noise": t["noise_level"],
            "expected": expected, "also": also,
            "predicted": predicted, "supported": supported,
            "top1": predicted == expected,
            "contributing_found": (also in supported) if also else None,
            "wave1": len((r.get("wave_plan") or {}).get("wave1", [])),
            "second_wave": "request_second_pass" in actions,
            "revisions": actions.count("request_revision"),
            "escalated": "escalate_to_pharmacist" in actions,
            "status": r.get("status"),
        })

    n = len(rows)
    summary = {
        "cases": n,
        "top1_accuracy": round(sum(r["top1"] for r in rows) / n, 3),
        "contributing_cause_recall": (
            f"{sum(1 for r in rows if r['contributing_found'])}/"
            f"{sum(1 for r in rows if r['contributing_found'] is not None)}"
        ),
        "evaluator_revisions": sum(r["revisions"] for r in rows),
        "cases_needing_second_wave": sum(r["second_wave"] for r in rows),
        "escalations": sum(r["escalated"] for r in rows),
        "mean_wave1_investigators": round(sum(r["wave1"] for r in rows) / n, 1),
        "llm": "Nightshift" if llm_enabled() else "off (rule-based reasoning)",
    }
    (ROOT / "eval/results.json").write_text(
        json.dumps({"summary": summary, "cases": rows}, indent=2) + "\n"
    )
    md = [
        "# Back-test results", "",
        "Generated by `python scripts/evaluate.py`. Synthetic data; the rules were "
        "written while looking at these same 16 cases, so treat this as a "
        "regression check, not proof of accuracy on real data.", "",
        "| Metric | Value |", "|---|---|",
    ]
    md += [f"| {k} | {v} |" for k, v in summary.items()]
    md += ["", "| Case | Noise | Expected | Predicted | Supported causes | Top-1 | Contributing found |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        contrib = "" if r["contributing_found"] is None else ("yes" if r["contributing_found"] else "no")
        md.append(
            f"| {r['dataset'].split('cases/')[1]} | {r['noise']} | {r['expected']}"
            f"{' + ' + r['also'] if r['also'] else ''} | {r['predicted']} | "
            f"{', '.join(r['supported'])} | {'yes' if r['top1'] else 'NO'} | {contrib} |"
        )
    (ROOT / "eval/RESULTS.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
